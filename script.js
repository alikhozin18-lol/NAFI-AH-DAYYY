let startX = 0;

let startY = 0;


document.addEventListener(
    "touchstart",
    event => {

        startX =
            event.changedTouches[0]
                .screenX;

        startY =
            event.changedTouches[0]
                .screenY;

    },
    {
        passive: true
    }
);


document.addEventListener(
    "touchend",
    event => {

        const endX =
            event.changedTouches[0]
                .screenX;

        const endY =
            event.changedTouches[0]
                .screenY;


        const diffX =
            startX - endX;

        const diffY =
            startY - endY;


        if(
            Math.abs(diffX) < 60 ||
            Math.abs(diffX) <
            Math.abs(diffY)
        ) {

            return;

        }


        if(
            quizScreen.classList.contains("show") ||
            quizIntro.classList.contains("show") ||
            verdictScreen.classList.contains("show") ||
            finalScreen.classList.contains("show")
        ) {

            return;

        }


        if(diffX > 0) {

            if(
                currentPhoto <
                CONFIG.photos.length - 1
            ) {

                showPhoto(
                    currentPhoto + 1
                );

            }

            else {

                openQuizIntro();

            }

        }

        else {

            if(currentPhoto > 0) {

                showPhoto(
                    currentPhoto - 1
                );

            }

        }

    },
    {
        passive: true
    }
);


