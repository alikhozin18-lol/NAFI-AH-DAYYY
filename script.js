function playSound(audio) {

    if(!audio) return;

    audio.currentTime = 0;

    audio.volume = .8;

    audio.play()
        .catch(() => {});

}


/* =========================================================
   FADE OUT
========================================================= */

function fadeOut(audio, duration = 1000) {

    if(!audio) return;

    const startVolume =
        audio.volume;

    const steps = 25;

    const interval =
        duration / steps;

    let step = 0;

    const timer =
        setInterval(() => {

            step++;

            audio.volume =
                Math.max(
                    0,
                    startVolume *
                    (1 - step / steps)
                );

            if(step >= steps) {

                clearInterval(timer);

                audio.pause();

            }

        }, interval);

}


/* =========================================================
   FADE IN
========================================================= */

function fadeIn(audio, duration = 1500) {

    if(!audio) return;

    audio.volume = 0;

    audio.play()
        .catch(() => {});

    const steps = 30;

    const interval =
        duration / steps;

    let step = 0;

    const timer =
        setInterval(() => {

            step++;

            audio.volume =
                Math.min(
                    .6,
                    .6 *
                    (step / steps)
                );

            if(step >= steps) {

                clearInterval(timer);

            }

        }, interval);

}


